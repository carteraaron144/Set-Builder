// Writes packs/setbuilder-basics from the models built in src/assets/basicsModels.ts.
// Run: npm run make-pack   (Node 26 strips the types)
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

// GLTFExporter reads Blobs with FileReader, which Node doesn't have.
class FileReaderShim {
  result: ArrayBuffer | string | null = null
  onloadend: (() => void) | null = null
  readAsArrayBuffer(blob: Blob) {
    void blob.arrayBuffer().then((b) => {
      this.result = b
      this.onloadend?.()
    })
  }
  readAsDataURL(blob: Blob) {
    void blob.arrayBuffer().then((b) => {
      this.result = `data:${blob.type || 'application/octet-stream'};base64,${Buffer.from(b).toString('base64')}`
      this.onloadend?.()
    })
  }
}
;(globalThis as Record<string, unknown>).FileReader ??= FileReaderShim

const { GLTFExporter } = await import('three/addons/exporters/GLTFExporter.js')
const { basicsModels } = await import('../src/assets/basicsModels.ts')

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../packs/setbuilder-basics')
mkdirSync(resolve(root, 'models'), { recursive: true })

const models = basicsModels()
const exporter = new GLTFExporter()
for (const { asset, object } of models) {
  object.name = asset.id
  const glb = (await exporter.parseAsync(object, { binary: true })) as ArrayBuffer
  writeFileSync(resolve(root, asset.file), Buffer.from(glb))
  console.log(`${asset.file}  ${glb.byteLength} bytes`)
}

const manifest = {
  name: 'Set Builder Basics',
  version: '1.0.0',
  source: 'Generated by Set Builder (web/scripts/makeBasicsPack.ts)',
  licence: 'CC0-1.0',
  assets: models.map((m) => m.asset),
}
writeFileSync(resolve(root, 'pack.json'), JSON.stringify(manifest, null, 2) + '\n')
writeFileSync(
  resolve(root, 'LICENSE.txt'),
  'Set Builder Basics is dedicated to the public domain under CC0 1.0 Universal.\n' +
    'https://creativecommons.org/publicdomain/zero/1.0/\n',
)
console.log(`wrote ${models.length} models to ${root}`)
